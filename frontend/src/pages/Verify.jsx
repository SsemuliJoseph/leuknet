import { useEffect, useState } from "react";
import { Link, useParams } from "react-router-dom";
import { errorMessage, verifyApi } from "../services/api.js";
import { formatDate, indicationLabel, resultLabel, resultTone } from "../utils.js";

export default function Verify() {
  const { token } = useParams();
  const [data, setData] = useState(null);
  const [error, setError] = useState(null);

  useEffect(() => {
    verifyApi.check(token).then(setData).catch((e) => setError(errorMessage(e)));
  }, [token]);

  return (
    <div className="verify-wrap verify-dark">
      <div className="card verify-card">
        {!data && !error && <div className="empty"><span className="spinner" /><p>Checking report...</p></div>}
        {error && <div className="alert error">{error}</div>}

        {data && !data.valid && (
          <>
            <div className="verify-icon">❌</div>
            <h1>Report not found</h1>
            <p className="muted">This code does not match any report issued by this LeukNet system. The document may be forged or the code mistyped.</p>
          </>
        )}

        {data?.valid && (
          <>
            <div className="verify-icon">✅</div>
            <h1>Report is Valid</h1>
            <p className="muted">Generated by the LeukNet system at <strong>{data.facility_name}</strong></p>
            <div className="kv" style={{ textAlign: "left", margin: "1rem 0" }}>
              <div>Patient</div><div>{data.patient_name}</div>
              <div>Gender / Age</div><div>{data.gender}, {data.age} yrs</div>
              <div>Test</div><div>{data.test_name}</div>
              <div>Issued</div><div>{formatDate(data.issued_at)}</div>
              <div>Samples</div><div>{data.images_analyzed}</div>
              <div>Foreign objects</div><div>{data.foreign_objects}</div>
              <div>Report ID</div><div style={{ wordBreak: "break-all" }}>{data.report_id}</div>
            </div>
            <div className={`result-banner ${resultTone(data.result)}`} style={{ marginBottom: ".8rem", textAlign: "left" }}>
              <strong>{resultLabel(data.result, data.total_blasts)}</strong>
              {data.result === "blast_detected" && indicationLabel(data.indication) && <div>{indicationLabel(data.indication)}</div>}
            </div>
            <p className="small muted" style={{ textAlign: "left" }}>{data.summary}</p>
          </>
        )}
        <p className="small"><Link to="/">LeukNet home</Link></p>
      </div>
    </div>
  );
}
